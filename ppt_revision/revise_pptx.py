from pptx import Presentation

SRC = r"D:\AI\14 - 数据治理\ppt_revision\AI_主数据治理_v2.pptx"
DST = r"D:\AI\14 - 数据治理\ppt_revision\AI_主数据治理_v3.pptx"

prs = Presentation(SRC)


def set_para_text(para, text):
    """保留第一个 run 的格式，替换整段文字；删除多余 run。"""
    runs = list(para.runs)
    if runs:
        runs[0].text = text
        for r in runs[1:]:
            r._r.getparent().remove(r._r)
    else:
        run = para.add_run()
        run.text = text


def remove_para(para):
    para._p.getparent().remove(para._p)


def find_shape(slide, name):
    for sh in slide.shapes:
        if sh.name == name and sh.has_text_frame:
            return sh
    raise ValueError(f"shape not found: {name}")


def edit(slide_num, shape_name, sets=None, removes=None):
    """sets: {para_idx: new_text}; removes: [para_idx]"""
    slide = prs.slides[slide_num - 1]
    shape = find_shape(slide, shape_name)
    tf = shape.text_frame
    paras = list(tf.paragraphs)
    if sets:
        for idx, txt in sets.items():
            set_para_text(paras[idx], txt)
    if removes:
        # 从大到小删除，避免索引错位
        for idx in sorted(removes, reverse=True):
            remove_para(paras[idx])


